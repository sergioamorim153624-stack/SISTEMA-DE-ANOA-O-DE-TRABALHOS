import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { existsSync, readFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { resolve } from 'node:path';

test('página estática executa, salva e restaura serviços sem fazer chamadas de API',async t=>{
  const html=readFileSync(resolve('standalone/index.html'));
  const server=createServer((req,res)=>{res.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});res.end(html);}).listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const origin=`http://127.0.0.1:${server.address().port}`;
  const executablePath=process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined);
  const browser=await chromium.launch({executablePath,args:['--no-sandbox']});
  t.after(()=>browser.close());
  const context=await browser.newContext();
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const network=[];page.on('request',r=>{if(r.url().startsWith('http') && r.url() !== `${origin}/`)network.push(r.url());});
  await page.goto(origin);
  await page.getByRole('heading',{name:'Visão geral',exact:true}).waitFor();
  await page.getByRole('button',{name:'Novo serviço',exact:true}).click();
  let modal=page.getByRole('dialog');
  await modal.getByRole('button',{name:'Sites',exact:true}).click();
  await modal.getByRole('radio').filter({hasText:'Simples'}).click();
  await modal.getByLabel('Título do serviço').fill('Primeiro serviço online');
  await modal.getByRole('button',{name:'Criar serviço',exact:true}).click();
  for(const action of ['Iniciar serviço','Finalizar trabalho','Registrar entrega','Recebi o pagamento']) await modal.getByRole('button',{name:action,exact:true}).click();
  await modal.getByText('Pagamento recebido',{exact:true}).first().waitFor();
  await modal.getByRole('button',{name:'Fechar',exact:true}).click();
  await page.reload();
  await page.getByRole('button',{name:'Primeiro serviço online',exact:true}).waitFor();
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('nexo.workspace.v1')));
  const task=saved.records.find(([kind])=>kind==='task')[2];
  assert.equal(task.status,'delivered');assert.ok(task.paidAt);
  await page.getByRole('button',{name:'Configurações',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Exportar backup',exact:true}).click();const download=await downloadPromise;
  const filename=await download.path();
  await page.evaluate(()=>localStorage.clear());await page.reload();
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('input[type=file]').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:await (await import('node:fs/promises')).readFile(filename)});
  await page.getByRole('status').filter({hasText:'1 serviços importados'}).waitFor();
  await page.getByRole('button',{name:'Meus serviços',exact:true}).click();
  await page.getByRole('button',{name:'Primeiro serviço online',exact:true}).waitFor();
  await page.screenshot({path:'/tmp/nexo-standalone-verified.png',fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
});
